//! Deterministic generation of a standalone native build project.
//!
//! `recompile-elf --native-build` and `compile-cfg-fixture --native-build`
//! write `<stem>.native/CMakeLists.txt` and `<stem>.native/probe_main.cpp`
//! beside the translation. The project compiles the dispatcher, every part and
//! a host probe with an explicit runtime include directory, then registers a
//! CTest that loads the RAM image (when present) and performs one bounded
//! `execute_cfg` call.
//!
//! The renderer is pure: identical arguments produce identical files, and no
//! absolute paths, timestamps, or machine identifiers are embedded. The
//! generated project references its sibling translation files through `..`, so
//! the translation directory and `<stem>.native/` move together.

use crate::VERSION;

/// Rendered native build project.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NativeProject {
    pub cmake_lists: String,
    pub probe_source: String,
}

/// Renders a native CMake project for one translation layout.
///
/// `project_stem` is the translation output stem used to derive a CMake project
/// name. `sources` lists the dispatcher first and parts afterwards. `ram_image`
/// is the RAM file name recorded in the probe default, or `None` for synthetic
/// fixtures that execute against zero-filled RAM.
#[must_use]
pub fn render(project_stem: &str, sources: &[String], ram_image: Option<&str>) -> NativeProject {
    NativeProject {
        cmake_lists: render_cmake_lists(project_stem, sources, ram_image),
        probe_source: render_probe_source(ram_image),
    }
}

/// Derives a CMake-safe project name from an output stem.
#[must_use]
pub fn project_name(stem: &str) -> String {
    let mut name = String::from("reps2_");
    name.extend(stem.chars().map(|character| {
        if character.is_ascii_alphanumeric() {
            character
        } else {
            '_'
        }
    }));
    if name == "reps2_" {
        name.push_str("generated");
    }
    name
}

fn cmake_quote(value: &str) -> String {
    let mut output = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '\\' => output.push('/'),
            '"' => output.push_str("\\\""),
            '$' => output.push_str("\\$"),
            ';' => output.push_str("\\;"),
            character => output.push(character),
        }
    }
    output
}

fn cpp_string_literal(value: &str) -> String {
    let mut output = String::with_capacity(value.len() + 2);
    output.push('"');
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            character => output.push(character),
        }
    }
    output.push('"');
    output
}

fn render_cmake_lists(project_stem: &str, sources: &[String], ram_image: Option<&str>) -> String {
    let source_lines = sources
        .iter()
        .map(|name| format!("    \"../{}\"", cmake_quote(name)))
        .collect::<Vec<_>>()
        .join("\n");
    let test = match ram_image {
        Some(name) => format!(
            "add_test(NAME reps2_generated_probe\n    COMMAND reps2_probe \"${{CMAKE_CURRENT_SOURCE_DIR}}/../{}\" 0)",
            cmake_quote(name)
        ),
        None => "add_test(NAME reps2_generated_probe COMMAND reps2_probe)".to_owned(),
    };

    const TEMPLATE: &str = r#"# Generated by reps2-frontend @VERSION@. Do not edit.
cmake_minimum_required(VERSION 3.25)
project(@PROJECT@ LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)

set(REPS2_RUNTIME_INCLUDE "" CACHE PATH "Directory containing reps2/runtime/*.hpp")
if(NOT REPS2_RUNTIME_INCLUDE)
    message(FATAL_ERROR "Set -DREPS2_RUNTIME_INCLUDE=<path>/runtime/include")
endif()

add_executable(reps2_probe
@SOURCES@
    "probe_main.cpp"
)
target_include_directories(reps2_probe PRIVATE "${REPS2_RUNTIME_INCLUDE}")
target_compile_features(reps2_probe PRIVATE cxx_std_20)
if(MSVC)
    target_compile_options(reps2_probe PRIVATE /W4 /permissive-)
else()
    target_compile_options(reps2_probe PRIVATE -Wall -Wextra -Wpedantic -Wconversion)
endif()

enable_testing()
@TEST@
set_tests_properties(reps2_generated_probe PROPERTIES
    WORKING_DIRECTORY "${CMAKE_CURRENT_SOURCE_DIR}/.."
)
"#;

    TEMPLATE
        .replace("@VERSION@", VERSION)
        .replace("@PROJECT@", &project_name(project_stem))
        .replace("@SOURCES@", &source_lines)
        .replace("@TEST@", &test)
}

fn render_probe_source(ram_image: Option<&str>) -> String {
    let default_image = ram_image
        .map(cpp_string_literal)
        .unwrap_or_else(|| "nullptr".to_owned());

    const TEMPLATE: &str = r#"// Generated by reps2-frontend @VERSION@. Do not edit.
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <span>
#include <utility>
#include <vector>

#include "reps2/runtime/ee_state.hpp"

namespace reps2::generated {
[[nodiscard]] reps2::runtime::Status initialize_ee_state(
    reps2::runtime::EeState& state,
    std::span<const std::uint8_t> main_ram_image) noexcept;
[[nodiscard]] reps2::runtime::Status execute_cfg(
    reps2::runtime::EeState& state,
    std::uint64_t instruction_budget) noexcept;
} // namespace reps2::generated

namespace {

bool load_image(const char* path, std::vector<std::uint8_t>& bytes) {
    std::ifstream stream(path, std::ios::binary | std::ios::ate);
    if (!stream) {
        return false;
    }
    const std::streamoff size = static_cast<std::streamoff>(stream.tellg());
    if (size < 0) {
        return false;
    }
    bytes.resize(static_cast<std::size_t>(size));
    stream.seekg(0, std::ios::beg);
    stream.read(
        reinterpret_cast<char*>(bytes.data()),
        static_cast<std::streamsize>(bytes.size()));
    return stream.good();
}

} // namespace

int main(int argc, char** argv) {
    using reps2::runtime::Status;

    const char* image_path = (argc > 1) ? argv[1] : @DEFAULT_IMAGE@;
    std::uint64_t budget = 0;
    if (argc > 2) {
        char* end = nullptr;
        budget = static_cast<std::uint64_t>(std::strtoull(argv[2], &end, 0));
        if (end == argv[2] || *end != '\0') {
            std::fprintf(stderr, "invalid instruction budget: %s\n", argv[2]);
            return 2;
        }
    }

    std::vector<std::uint8_t> initial(reps2::runtime::kEeMainRamSize, 0);
    if (image_path != nullptr) {
        std::vector<std::uint8_t> loaded;
        if (!load_image(image_path, loaded)) {
            std::fprintf(stderr, "cannot read RAM image: %s\n", image_path);
            return 2;
        }
        if (loaded.size() != reps2::runtime::kEeMainRamSize) {
            std::fprintf(
                stderr,
                "RAM image has %zu bytes; expected %zu\n",
                loaded.size(),
                static_cast<std::size_t>(reps2::runtime::kEeMainRamSize));
            return 2;
        }
        initial = std::move(loaded);
    }

    std::vector<std::uint8_t> ram(reps2::runtime::kEeMainRamSize, 0);
    reps2::runtime::EeState state{};
    state.memory.main_ram = std::span<std::uint8_t>(ram.data(), ram.size());

    const Status init = reps2::generated::initialize_ee_state(
        state,
        std::span<const std::uint8_t>(initial.data(), initial.size()));
    if (init != Status::ok) {
        std::printf("init=%d\n", static_cast<int>(init));
        return 1;
    }

    const std::uint32_t entry = state.pc;
    const Status status = reps2::generated::execute_cfg(state, budget);
    std::printf(
        "entry=0x%08X status=%d pc=0x%08X budget=%llu\n",
        static_cast<unsigned>(entry),
        static_cast<int>(status),
        static_cast<unsigned>(state.pc),
        static_cast<unsigned long long>(budget));
    return 0;
}
"#;

    TEMPLATE
        .replace("@VERSION@", VERSION)
        .replace("@DEFAULT_IMAGE@", &default_image)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sources() -> Vec<String> {
        vec!["game.cpp".to_owned(), "game.part0001.cpp".to_owned()]
    }

    #[test]
    fn renders_ordered_sources_and_named_probe_test() {
        let project = render("game", &sources(), Some("game.ram.bin"));
        assert!(project.cmake_lists.contains(
            "add_executable(reps2_probe\n    \"../game.cpp\"\n    \"../game.part0001.cpp\"\n    \"probe_main.cpp\""
        ));
        assert!(project.cmake_lists.contains(
            "add_test(NAME reps2_generated_probe\n    COMMAND reps2_probe \"${CMAKE_CURRENT_SOURCE_DIR}/../game.ram.bin\" 0)"
        ));
        assert!(
            project
                .cmake_lists
                .contains("project(reps2_game LANGUAGES CXX)")
        );
        assert!(
            project
                .probe_source
                .contains("const char* image_path = (argc > 1) ? argv[1] : \"game.ram.bin\";")
        );
    }

    #[test]
    fn omits_ram_image_for_synthetic_fixtures() {
        let project = render("fixture", &sources(), None);
        assert!(
            project
                .cmake_lists
                .contains("add_test(NAME reps2_generated_probe COMMAND reps2_probe)")
        );
        assert!(!project.cmake_lists.contains(".ram.bin"));
        assert!(
            project
                .probe_source
                .contains("const char* image_path = (argc > 1) ? argv[1] : nullptr;")
        );
    }

    #[test]
    fn sanitizes_project_names() {
        assert_eq!(project_name("game"), "reps2_game");
        assert_eq!(project_name("a b/c.d"), "reps2_a_b_c_d");
        assert_eq!(project_name(""), "reps2_generated");
        assert_eq!(project_name("---"), "reps2____");
    }

    #[test]
    fn escapes_cmake_and_cpp_strings() {
        let names = vec!["a\"b.cpp".to_owned()];
        let project = render("weird", &names, Some("r\"m.bin"));
        assert!(project.cmake_lists.contains("\"../a\\\"b.cpp\""));
        assert!(project.probe_source.contains(": \"r\\\"m.bin\";"));
    }

    #[test]
    fn probe_exposes_the_runtime_boundary_and_bounded_execution() {
        let project = render("game", &sources(), Some("game.ram.bin"));
        assert!(
            project
                .probe_source
                .contains("#include \"reps2/runtime/ee_state.hpp\"")
        );
        assert!(project.probe_source.contains("initialize_ee_state("));
        assert!(project.probe_source.contains("execute_cfg(state, budget)"));
        assert!(project.probe_source.contains("kEeMainRamSize"));
        assert!(project.probe_source.contains("instruction budget"));
    }

    #[test]
    fn rendering_is_deterministic() {
        let first = render("game", &sources(), Some("game.ram.bin"));
        let second = render("game", &sources(), Some("game.ram.bin"));
        assert_eq!(first, second);
        assert!(!first.cmake_lists.contains("timestamp"));
    }
}
