//! C++20 lowering for the verified CFG-aware control-flow IR.
//!
//! This backend emits a bounded dispatcher. Static targets inside the
//! translated graph continue natively; unresolved/dynamic targets are written
//! to EeState::pc and returned to the caller as external control flow.
//!
//! Every basic block becomes its own `reps2::generated::block_0xXXXXXXXX`
//! function. `execute_cfg` binary-searches a sorted block table and calls the
//! matching function, so dispatch cost is logarithmic and each block is an
//! independent, cache-friendly unit. A large program can be emitted as several
//! translation units: one dispatcher holding the table and one file per block
//! slice. The partitioned files share nothing but the runtime header and can
//! be compiled in parallel.

use crate::analysis::DelaySlotPolicy;
use crate::control_ir::{ControlBlock, ControlError, ControlProgram, ControlTerminator, TrapKind};

/// Shared prelude for every emitted translation unit.
