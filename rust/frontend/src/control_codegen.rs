const NAMESPACE_CLOSE: &str = "} // namespace reps2::generated\n";

/// Params shared by the block declarations and definitions.
const BLOCK_PARAMS: &str =
    "    reps2::runtime::EeState& state,\n    std::uint64_t& remaining\n) noexcept";

/// `execute_cfg` body: sort-order lookup over the block table, then dispatch.
const EXECUTE_CFG: &str = "\
struct BlockEntry {
    std::uint32_t pc;
    reps2::runtime::Status (*function)(
        reps2::runtime::EeState& state,
        std::uint64_t& remaining
    ) noexcept;
};

constexpr BlockEntry kBlocks[] = {
";

const EXECUTE_CFG_TAIL: &str = "\
};

[[nodiscard]] reps2::runtime::Status execute_cfg(
    reps2::runtime::EeState& state,
    std::uint64_t instruction_budget
) noexcept {
    std::uint64_t remaining = instruction_budget;
    state.gpr[0] = {};
    const BlockEntry* const begin = std::begin(kBlocks);
    const BlockEntry* const end = std::end(kBlocks);
    for (;;) {
        const BlockEntry* const found = std::lower_bound(
            begin, end, state.pc,
            [](const BlockEntry& entry, std::uint32_t pc) { return entry.pc < pc; });
        if (found == end || found->pc != state.pc) {
            return Status::external_control_flow;
        }
        const Status status = found->function(state, remaining);
        if (status != Status::ok) {
            return status;
        }
    }
}

";

/// Emits a deterministic single C++20 translation unit with execute_cfg().
pub fn emit_cpp(program: &ControlProgram) -> Result<String, ControlError> {
    emit_cpp_units(program, 1)?
        .into_iter()
        .next()
        .ok_or(ControlError::InvalidTranslationUnitCount(0))
}

/// Emits the CFG dispatcher plus the ELF entry-point/RAM-image initializer.
/// The adjacent .ram.bin file is supplied by the host as a 32 MiB byte span.
pub fn emit_cpp_with_entry(
    program: &ControlProgram,
    guest_entry_pc: u32,
) -> Result<String, ControlError> {
    emit_cpp_units_with_entry(program, guest_entry_pc, 1)?
        .into_iter()
        .next()
        .ok_or(ControlError::InvalidTranslationUnitCount(0))
}

/// Emits a program split across `tu_count` translation units.
///
/// The returned vector always has units[0] as the file the caller should write
/// to the primary output path. When `tu_count` is one this is a single
/// self-contained unit. When it is greater than one, units[0] is the dispatcher
/// (block table and `execute_cfg`) and units[1..] hold the block definitions,
/// ordered by ascending guest PC. `tu_count` must be at least one and at most
/// the number of blocks.
pub fn emit_cpp_units(
    program: &ControlProgram,
    tu_count: usize,
) -> Result<Vec<String>, ControlError> {
    program.verify()?;
    if tu_count == 0 || tu_count > program.blocks.len() {
        return Err(ControlError::InvalidTranslationUnitCount(tu_count));
    }

    if tu_count == 1 {
        return Ok(vec![emit_single_unit(program)]);
    }

    let mut dispatcher = String::from(SOURCE_PRELUDE);
    emit_block_declarations(&mut dispatcher, program);
    emit_block_table(&mut dispatcher, program);
    dispatcher.push_str(EXECUTE_CFG_TAIL);
    dispatcher.push_str(NAMESPACE_CLOSE);

    let mut units = Vec::with_capacity(tu_count + 1);
    units.push(dispatcher);
    for slice in block_slices(program, tu_count) {
        units.push(emit_block_unit(program, &slice));
    }
    Ok(units)
}

/// Emits the partitioned translation units plus the ELF entry-point initializer.
///
/// The initializer is appended to units[0] (the dispatcher, or the single
/// self-contained unit when `tu_count` is one).
pub fn emit_cpp_units_with_entry(
    program: &ControlProgram,
    guest_entry_pc: u32,
    tu_count: usize,
) -> Result<Vec<String>, ControlError> {
    if !program.blocks.contains_key(&guest_entry_pc)
        || !program.entry_points.contains(&guest_entry_pc)
    {
        return Err(ControlError::InvalidEntryPoint(guest_entry_pc));
    }

    let mut units = emit_cpp_units(program, tu_count)?;
    units[0].push_str(&entry_initializer(guest_entry_pc));
    Ok(units)
}

fn emit_single_unit(program: &ControlProgram) -> String {
    let mut output = String::from(SOURCE_PRELUDE);
    emit_block_declarations(&mut output, program);
    emit_block_table(&mut output, program);
    output.push_str(EXECUTE_CFG_TAIL);
    for block in program.blocks.values() {
        emit_block_definition(&mut output, block);
    }
    output.push_str(NAMESPACE_CLOSE);
    output
}

fn emit_block_unit(program: &ControlProgram, pcs: &[u32]) -> String {
    let mut unit = String::from(SOURCE_PRELUDE);
    for pc in pcs {
        emit_block_definition(&mut unit, &program.blocks[pc]);
    }
    unit.push_str(NAMESPACE_CLOSE);
    unit
}

/// Evenly partitions the sorted block PCs into `tu_count` non-empty slices.
fn block_slices(program: &ControlProgram, tu_count: usize) -> Vec<Vec<u32>> {
    let pcs: Vec<u32> = program.blocks.keys().copied().collect();
    let total = pcs.len();
    (0..tu_count)
        .map(|index| pcs[index * total / tu_count..(index + 1) * total / tu_count].to_vec())
        .collect()
}

fn emit_block_declarations(output: &mut String, program: &ControlProgram) {
    for pc in program.blocks.keys() {
        output.push_str(&format!(
            "[[nodiscard]] reps2::runtime::Status block_0x{pc:08X}(\n\
             {BLOCK_PARAMS};\n"
        ));
    }
    output.push('\n');
}

fn emit_block_table(output: &mut String, program: &ControlProgram) {
    output.push_str(EXECUTE_CFG);
    for pc in program.blocks.keys() {
        output.push_str(&format!("    {{0x{pc:08X}U, &block_0x{pc:08X}}},\n"));
    }
}

fn emit_block_definition(output: &mut String, block: &ControlBlock) {
    let pc = block.start_pc;
    let required = block.instructions.len() + block.terminator.instruction_count();
    output.push_str(&format!(
        "[[nodiscard]] reps2::runtime::Status block_0x{pc:08X}(\n\
         {BLOCK_PARAMS} {{\n\
         \x20   if (remaining < {required}ULL) return Status::instruction_budget_exhausted;\n\
         \x20   remaining -= {required}ULL;\n"
    ));

    for (instruction_index, instruction) in block.instructions.iter().enumerate() {
        output.push_str(&format!(
            "    state.pc = 0x{:08X}U;\n",
            instruction.guest_pc
        ));
        crate::codegen::emit_instruction(output, instruction_index, *instruction);
    }

    emit_terminator(output, &block.terminator, block.instructions.len());
    output.push_str("}\n\n");
}

fn entry_initializer(guest_entry_pc: u32) -> String {
    format!(
        "\nnamespace reps2::generated {{\n\
         [[nodiscard]] reps2::runtime::Status initialize_ee_state(\n\
             reps2::runtime::EeState& state,\n\
             std::span<const std::uint8_t> main_ram_image\n\
         ) noexcept {{\n\
             return reps2::runtime::initialize_ee_state(state, main_ram_image, 0x{guest_entry_pc:08X}U);\n\
         }}\n\
         }} // namespace reps2::generated\n"
    )
}

fn emit_terminator(output: &mut String, terminator: &ControlTerminator, index: usize) {
    match terminator {
        ControlTerminator::Fallthrough { next_pc } => {
            output.push_str(&format!(
                "    state.pc = 0x{next_pc:08X}U;\n    return Status::ok;\n"
            ));
        }
        ControlTerminator::ConditionalBranch {
            guest_pc,
            condition,
            target_pc,
            fallthrough_pc,
            link_register,
            delay_slot,
            delay_slot_policy,
        } => {
            output.push_str(&format!(
                "    state.pc = 0x{guest_pc:08X}U;\n\
                 \x20   const bool branch_taken_{guest_pc:08X} = {};\n",
                condition_expression(*condition)
            ));
            emit_link_write(output, *link_register, guest_pc.wrapping_add(8));
            match delay_slot_policy {
                DelaySlotPolicy::ExecuteAlways => emit_delay_slot(output, index, delay_slot),
                DelaySlotPolicy::AnnulWhenNotTaken => {
                    output.push_str(&format!("    if (branch_taken_{guest_pc:08X}) {{\n"));
                    emit_delay_slot(output, index, delay_slot);
                    output.push_str("    }\n");
                }
            }
            output.push_str(&format!(
                "    state.pc = branch_taken_{guest_pc:08X} ? 0x{target_pc:08X}U : 0x{fallthrough_pc:08X}U;\n\
                 \x20   return Status::ok;\n"
            ));
        }
        ControlTerminator::DirectJump {
            guest_pc,
            target_pc,
            link_register,
            return_pc,
            delay_slot,
        } => {
            output.push_str(&format!("    state.pc = 0x{guest_pc:08X}U;\n"));
            emit_link_write(
                output,
                *link_register,
                return_pc.unwrap_or(guest_pc.wrapping_add(8)),
            );
            emit_delay_slot(output, index, delay_slot);
            output.push_str(&format!(
                "    state.pc = 0x{target_pc:08X}U;\n    return Status::ok;\n"
            ));
        }
        ControlTerminator::IndirectJump {
            guest_pc,
            source_register,
            link_register,
            return_pc,
            delay_slot,
        } => {
            // Capture the dynamic target before a potentially aliased link write.
            output.push_str(&format!(
                "    state.pc = 0x{guest_pc:08X}U;\n\
                 \x20   const std::uint32_t dynamic_target_{guest_pc:08X} = static_cast<std::uint32_t>(state.gpr[{source_register}].low);\n"
            ));
            emit_link_write(
                output,
                *link_register,
                return_pc.unwrap_or(guest_pc.wrapping_add(8)),
            );
            emit_delay_slot(output, index, delay_slot);
            output.push_str(&format!(
                "    state.pc = dynamic_target_{guest_pc:08X};\n    return Status::ok;\n"
            ));
        }
        ControlTerminator::Return {
            guest_pc,
            source_register,
            delay_slot,
        } => {
            output.push_str(&format!(
                "    state.pc = 0x{guest_pc:08X}U;\n\
                 \x20   const std::uint32_t return_target_{guest_pc:08X} = static_cast<std::uint32_t>(state.gpr[{source_register}].low);\n"
            ));
            emit_delay_slot(output, index, delay_slot);
            output.push_str(&format!(
                "    state.pc = return_target_{guest_pc:08X};\n    return Status::ok;\n"
            ));
        }
        ControlTerminator::ExceptionReturn { guest_pc } => {
            output.push_str(&format!(
                "    state.pc = 0x{guest_pc:08X}U;\n    return return_from_ee_exception(state);\n"
            ));
        }
        ControlTerminator::GuestException { guest_pc, trap } => {
            output.push_str(&format!("    state.pc = 0x{guest_pc:08X}U;\n"));
            match trap {
                TrapKind::Syscall => output.push_str(
                    "    return raise_ee_exception(state, ExceptionCode::SystemCall);\n"
                ),
                TrapKind::Break => output.push_str(
                    "    return raise_ee_exception(state, ExceptionCode::Breakpoint);\n"
                ),
            }
        }
        ControlTerminator::Unsupported { guest_pc, .. } => {
            output.push_str(&format!(
                "    state.pc = 0x{guest_pc:08X}U;\n    return Status::unsupported_instruction;\n"
            ));
        }
        ControlTerminator::SegmentEnd { next_pc } => {
            output.push_str(&format!(
                "    state.pc = 0x{next_pc:08X}U;\n    return Status::external_control_flow;\n"
            ));
        }
    }
}

fn emit_link_write(output: &mut String, register: Option<u8>, return_pc: u32) {
    if let Some(register) = register
        && register != 0
    {
        output.push_str(&format!(
            "    state.gpr[{register}].low = static_cast<std::uint64_t>(0x{return_pc:08X}U);\n"
        ));
    }
}

fn emit_delay_slot(output: &mut String, index: usize, delay_slot: &crate::ir::Instruction) {
    output.push_str(&format!("    state.pc = 0x{:08X}U;\n", delay_slot.guest_pc));
    crate::codegen::emit_instruction(output, index, *delay_slot);
}

fn condition_expression(condition: crate::analysis::BranchCondition) -> String {
    use crate::analysis::BranchCondition;

    match condition {
        BranchCondition::Equal { lhs, rhs } => {
            format!("state.gpr[{lhs}].low == state.gpr[{rhs}].low")
        }
        BranchCondition::NotEqual { lhs, rhs } => {
            format!("state.gpr[{lhs}].low != state.gpr[{rhs}].low")
        }
        BranchCondition::LessThanOrEqualZero { register } => {
            format!("std::bit_cast<std::int64_t>(state.gpr[{register}].low) <= 0")
        }
        BranchCondition::GreaterThanZero { register } => {
            format!("std::bit_cast<std::int64_t>(state.gpr[{register}].low) > 0")
        }
        BranchCondition::LessThanZero { register } => {
            format!("std::bit_cast<std::int64_t>(state.gpr[{register}].low) < 0")
        }
        BranchCondition::GreaterThanOrEqualZero { register } => {
            format!("std::bit_cast<std::int64_t>(state.gpr[{register}].low) >= 0")
        }
        BranchCondition::FpuCondition { when_set } => {
            let relation = if when_set { "!=" } else { "==" };
            format!("(state.fcsr & reps2::runtime::kFpuCondition) {relation} 0")
        }
    }
}

